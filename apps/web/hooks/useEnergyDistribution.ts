"use client"

import { useState } from "react"
import { useWallet } from "@/lib/wallet-context"
import { CONTRACTS } from "@/lib/contracts-config"
import * as StellarSdk from "@stellar/stellar-sdk"
import { invokeContractWrite, simulateContractRead } from "@/lib/stellar/contract-client"
import { translateStellarError } from "@/hooks/useEnergyToken"
import {
  ChainUnavailableError,
  ChainWriteFailedError,
  ChainWritePendingError,
  isTransientChainError,
} from "@/lib/stellar/resilience"

export function useEnergyDistribution() {
  const { address } = useWallet()
  const write = useContractWrite()
  const [isLoading, setIsLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)

  const read = async <T,>(method: string, args: StellarSdk.xdr.ScVal[] = [], source?: string): Promise<T> => {
    try {
      setIsLoading(true)
      setError(null)
      const sourceAddress = source || address
      if (!sourceAddress) throw new Error("No wallet connected")
      if (!CONTRACTS.ENERGY_DISTRIBUTION) throw new Error("Energy distribution contract not configured")
      return await simulateContractRead<T>({
        contractId: CONTRACTS.ENERGY_DISTRIBUTION,
        method,
        args,
        sourceAddress,
      })
    } catch (err) {
      setError(err instanceof Error ? err.message : "Unknown error")
      console.error(`Error reading ${method}:`, err)
      throw err
    } finally {
      setIsLoading(false)
    }
  }

  /** Member share on the distribution contract. Throws on outage. */
  const getMemberInfo = async (memberAddress?: string) => {
    const targetAddress = memberAddress || address
    try {
      const percent = await read<number | null>(
        "get_member_percent",
        [StellarSdk.nativeToScVal(targetAddress, { type: "address" })],
        targetAddress ?? undefined,
      )
      return { isMember: percent !== null && percent !== undefined, percent: percent || 0 }
    } catch (err) {
      // A rejected simulation is a definitive "not a member"; an outage is not.
      if (!isTransientChainError(err) && err instanceof Error && err.message.startsWith("Simulation of")) {
        return { isMember: false, percent: 0 }
      }
      throw err
    }
  }

  /** Total kWh generated by the community, as recorded on-chain. */
  const getTotalGenerated = async (): Promise<number> => {
    const total = await read<bigint>("get_total_generated")
    return Number(total) / 1e7
  }

  /** Addresses registered on the distribution contract. */
  const getMemberList = async (): Promise<string[]> => read<string[]>("get_member_list")

  /** Record energy generation (admin only). Never retried as a whole. */
  const recordGeneration = async (kwhGenerated: number): Promise<string> => {
    try {
      setIsLoading(true)
      setError(null)
      if (!address || !kit) throw new Error("No wallet connected")
      if (!CONTRACTS.ENERGY_DISTRIBUTION) throw new Error("Energy distribution contract not configured")

      return await invokeContractWrite({
        operation: "distribution.record_generation",
        contractId: CONTRACTS.ENERGY_DISTRIBUTION,
        method: "record_generation",
        args: [StellarSdk.nativeToScVal(BigInt(Math.round(kwhGenerated * 1e7)), { type: "i128" })],
        sourceAddress: address,
        kit,
        description: `Record ${kwhGenerated} kWh`,
      })
    } catch (err) {
      const message = translateStellarError(err)
      setError(message)
      console.error("Error recording generation:", err)
      if (err instanceof ChainWritePendingError || err instanceof ChainUnavailableError || err instanceof ChainWriteFailedError) {
        throw err
      }
      throw new Error(message)
    } finally {
      setIsLoading(false)
    }
  }

  return {
    getMemberInfo,
    getMemberList,
    getTotalGenerated,
    recordGeneration,
    isLoading,
    error,
  }
}
